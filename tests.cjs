const assert = require('node:assert/strict');
const C = require('./core.js');
const parsed = C.parse('\uFEFFCompany,Notes,Value\r\n"A, B","said ""hi""\nagain",10\r\n');
assert.equal(parsed.rows[0][0], 'A, B');
assert.equal(parsed.rows[0][1], 'said "hi"\nagain');
assert.equal(parsed.rows.length, 1);
assert.throws(() => C.parse('a,b\n"unfinished,b'), /not closed/);
assert.throws(() => C.parse('a,b\n1,2,3'), /fields/);
assert.throws(() => C.parse('a\n"value"bad'), /quoting/);
assert.throws(() => C.parse(''), /empty/);
const data = C.parse('name,value,date\n Acme ,10,2026-01-01\nAcme,10,2026-01-01\nOther,,01\/02\/2026\n,,\n');
const report = C.analyse(data);
assert.equal(report.duplicates,1);assert.equal(report.missing,4);assert.equal(report.spaces,1);assert.equal(report.blank,1);assert.equal(report.mixed.length,1);
const cleaned = C.clean(data,{trim:true,dedupe:true,blank:true});
assert.equal(cleaned.rows.length,2);assert.equal(cleaned.changes.removedDuplicates,1);assert.equal(cleaned.changes.removedEmpty,1);
assert.equal(data.rows[0][0],' Acme ');
assert.equal(C.clean(data,{trim:false,dedupe:true,blank:false}).rows.length,4);
assert.deepEqual(C.parse(C.stringify(parsed,false)),parsed);
assert.match(C.stringify({headers:['x'],rows:[['=1+1']]},true), /'=1\+1/);
assert.equal(C.analyse(C.parse('a\n2026-02-30\nhello')).mixed.length,0);
assert.equal(C.parse('a,b\n\n1,2').rows[0].length,2);
console.log('All CSV parser, analysis, cleaning and export tests passed.');
